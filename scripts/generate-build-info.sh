#!/usr/bin/env bash
# Generate a build-time fingerprint from the checked-out Git revision.
# Called before xcodegen source discovery and before each Xcode compile.
set -euo pipefail
root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
output="$root/TypeTypeTV/TVBuildInfo.generated.swift"

if git -C "$root" rev-parse --verify HEAD >/dev/null 2>&1; then
    revision="$(git -C "$root" rev-parse HEAD)"
    branch="$(git -C "$root" symbolic-ref --short HEAD 2>/dev/null || printf 'detached')"
else
    revision="unknown"
    branch="unknown"
fi
short="${revision:0:12}"
# Quote Git branch names safely inside Swift string literals.
branch="${branch//\\/\\\\}"
branch="${branch//\"/\\\"}"

tmp="$(mktemp "${output}.XXXXXX")"
trap 'rm -f "$tmp"' EXIT
cat >"$tmp" <<EOF
// Automatically generated by scripts/generate-build-info.sh. Do not edit.
enum TVBuildInfo {
    static let gitRevision = "$revision"
    static let gitShortRevision = "$short"
    static let gitBranch = "$branch"
}
EOF
# No needless recompilation when building the same checked-out commit.
if ! cmp -s "$tmp" "$output"; then
    mv -f "$tmp" "$output"
fi
