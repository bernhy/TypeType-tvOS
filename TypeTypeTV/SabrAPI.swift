// TypeType Server API v1. This client does not depend on any server-side tvOS adaptation.
struct SabrBootstrap: Decodable {
    struct Video: Decodable {
        let itag: Int
        let codec: String
        let mimeType: String?
        let width: Int?
        let height: Int?
        let fps: Int?
        let bitrate: Int?
        let deliveryMethod: String?
    }
    struct Audio: Decodable {
        let itag: Int
        let codec: String?
        let mimeType: String?
        let audioTrackId: String?
        let audioTrackName: String?
        let audioLocale: String?
        let isOriginal: Bool?
        let deliveryMethod: String?
    }
    let id: String?
    let hlsUrl: String?
    let isLive: Bool?
    let videoOnlyStreams: [Video]?
    let audioStreams: [Audio]?
    var subtitles: [Subtitle]? = nil

    struct Subtitle: Decodable, Identifiable {
        let url: String
        let mimeType: String?
        let languageTag: String?
        let displayLanguageName: String?
        let isAutoGenerated: Bool?
        var id: String { url }
        var label: String {
            let preferred = displayLanguageName?.isEmpty == false
                ? displayLanguageName : languageTag
            return preferred ?? "?"
        }
    }
}

struct SabrSessionRequest: Encodable {
    let videoItag: Int
    let audioItag: Int
    let audioTrackId: String?
    let startTimeMs: Int64
    let playerTimeMs: Int64
    let audioOnly: Bool
    let isLive: Bool

    init(_ selected: SabrSelection, positionMs: Int64, live: Bool = false) {
        videoItag = selected.video.itag
        audioItag = selected.audio.itag
        audioTrackId = selected.audio.audioTrackId
        startTimeMs = positionMs
        playerTimeMs = positionMs
        audioOnly = false
        isLive = live
    }
}

struct SabrSessionReply: Decodable {
    let sessionId: String
    let generation: Int64
    let ready: Bool?
    let status: String?
    let retryAfterMs: Int?
}

struct SabrBufferedRange: Encodable {
    let itag: Int
    let startMs: Int64
    let endMs: Int64
}

struct SabrWindowRequest: Encodable {
    let generation: Int64
    let playerTimeMs: Int64
    let videoItag: Int
    let audioItag: Int
    let audioTrackId: String?
    let playbackRate: Float
    let bufferGoalMs: Int
    let backBufferMs: Int
    let bufferedRanges: [SabrBufferedRange]
    let audioOnly: Bool

    init(_ selected: SabrSelection, generation: Int64, positionMs: Int64,
         ranges: [SabrBufferedRange], buffer: SabrBufferSettings = SabrBufferSettings(),
         requestedBufferGoalMs: Int? = nil) {
        self.generation = generation
        playerTimeMs = positionMs
        videoItag = selected.video.itag
        audioItag = selected.audio.itag
        audioTrackId = selected.audio.audioTrackId
        playbackRate = 1
        // Honour the producer's bitrate-aware lookahead. Previously it
        // capped local prefetch at ~20–36s but still asked the server
        // to buffer 180s, causing avoidable server-side pump throttling.
        bufferGoalMs = min(buffer.forwardMilliseconds,
                           max(1_000, requestedBufferGoalMs ?? buffer.forwardMilliseconds))
        backBufferMs = buffer.backMilliseconds
        bufferedRanges = ranges
        audioOnly = false
    }
}

struct SabrFragment: Decodable, Hashable {
    let url: String
    let startMs: Int64
    let durationMs: Int64
}

struct SabrTrack: Decodable {
    let mime: String?
    let initUrl: String
    let segments: [SabrFragment]
}

struct SabrWindow: Decodable {
    let sessionId: String?
    let generation: Int64?
    let ready: Bool
    let retryAfterMs: Int?
    let status: String?
    let durationMs: Int64?
    let endOfStream: Bool?
    let startTimeMs: Int64?
    let audio: SabrTrack?
    let video: SabrTrack?
    let terminalError: String?
    let recoveryAction: String?
    let retryVideoItags: [Int]?
}

struct SabrSelection {
    let video: SabrBootstrap.Video
    let audio: SabrBootstrap.Audio
    var description: String {
        let height = video.height.map { "\($0)p" } ?? "Video"
        // A missing frame-rate in the server bootstrap is *unknown*, not 0.
        let frameRate: String
        if let fps = video.fps, fps > 0 {
            frameRate = " @ \(fps)fps"
        } else {
            frameRate = ""
        }
        return "\(video.codec) \(height)\(frameRate) (itag \(video.itag))"
    }
}

/// Device pairing errors are separate from video playback failures.
enum DeviceLoginError: LocalizedError {
    case serverUnsupported

    var errorDescription: String? {
        TVL10n.value("login.deviceServerUnsupported")
    }
}

enum SabrFailure: LocalizedError {
    case unsupported(String)
    case invalidResponse(String)
    case server(Int, String)
    case throttled(Int, String, Int)
    case unavailable
    case expired
    case stalled(String)
    case stopped

    var errorDescription: String? {
        switch self {
        case .unsupported(let value): return TVL10n.formatted("error.sabrUnsupported", value)
        case .invalidResponse(let value): return TVL10n.formatted("error.sabrReply", value)
        case .server(let code, let value): return TVL10n.formatted("error.sabrHTTP", code, value)
        case .throttled(let code, let value, _):
            return TVL10n.formatted("error.sabrHTTP", code, value)
        case .unavailable: return TVL10n.value("player.unavailable")
        case .expired: return TVL10n.value("error.sabrExpired")
        case .stalled(let detail): return TVL10n.formatted("error.sabrReply", detail)
        case .stopped: return TVL10n.value("error.sabrStopped")
        }
    }
}

// Strict by default: no software-only codecs silently selected for Apple TV 4K.
enum HardwareCodec {
    static func fourCC(_ codec: String) -> CMVideoCodecType? {
        let id = codec.lowercased()
        if id.hasPrefix("avc1") || id.hasPrefix("avc3") { return CMVideoCodecType(0x61766331) }
        if id.hasPrefix("hvc1") || id.hasPrefix("hev1") { return CMVideoCodecType(0x68766331) }
        if id.hasPrefix("vp9") || id.hasPrefix("vp09") { return CMVideoCodecType(0x76703039) }
        if id.hasPrefix("av01") { return CMVideoCodecType(0x61763031) }
        return nil
    }

    static func supported(_ codec: String, allowSoftware: Bool = false) -> Bool {
        guard let type = fourCC(codec) else { return false }
        return allowSoftware || VTIsHardwareDecodeSupported(type)
    }


    static func choose(from stream: SabrBootstrap,
                       maxHeight: Int = 2160,
                       allowSoftware: Bool = false) -> SabrSelection? {
        candidates(from: stream, maxHeight: maxHeight,
                   allowSoftware: allowSoftware).first
    }

    /// Codec-type hardware support is only a coarse probe. The actual
    /// VideoToolbox session will validate profile, level and bit depth.
    static func audioCandidates(from stream: SabrBootstrap) -> [SabrBootstrap.Audio] {
        let tracks = (stream.audioStreams ?? []).filter {
            $0.deliveryMethod == "sabr" && (
                ($0.codec ?? "").lowercased().hasPrefix("mp4a") ||
                ($0.mimeType ?? "").lowercased().contains("audio/mp4")
            )
        }
        var seen = Set<String>()
        return tracks.filter {
            let key = ($0.audioTrackId ?? "") + ":" + String($0.itag)
            return seen.insert(key).inserted
        }.sorted {
            if ($0.isOriginal ?? false) != ($1.isOriginal ?? false) {
                return $0.isOriginal ?? false
            }
            return ($0.audioTrackName ?? "") < ($1.audioTrackName ?? "")
        }
    }

    static func candidates(from stream: SabrBootstrap,
                           maxHeight: Int = 2160,
                           allowSoftware: Bool = false) -> [SabrSelection] {
        let available = (stream.videoOnlyStreams ?? []).filter {
            $0.deliveryMethod == "sabr" && ($0.height ?? 0) > 0
                && ($0.height ?? 0) <= maxHeight
                && ($0.fps ?? 0) <= 60
                && supported($0.codec, allowSoftware: allowSoftware)
        }
        let rank: (String) -> Int = { codec in
            let id = codec.lowercased()
            if id.hasPrefix("av01") { return 4 }
            if id.hasPrefix("hvc") || id.hasPrefix("hev") { return 3 }
            if id.hasPrefix("vp") { return 2 }
            return 1
        }
        let videos = available.sorted {
            if $0.height != $1.height { return ($0.height ?? 0) > ($1.height ?? 0) }
            if $0.fps != $1.fps { return ($0.fps ?? 0) > ($1.fps ?? 0) }
            return rank($0.codec) > rank($1.codec)
        }
        let audio = audioCandidates(from: stream).first
        guard let audio else { return [] }
        var used = Set<Int>()
        // The quality menu must offer every hardware-compatible SABR
        // format. The former .prefix(8) silently hid AVC/VP9/HEVC whenever
        // the server supplied eight higher-resolution AV1 representations.
        // This is a user choice, not a fallback list to artificially cap.
        return videos.filter { used.insert($0.itag).inserted }
            .map { SabrSelection(video: $0, audio: audio) }
    }
}

final class TypeTypeCredentials {
    static let shared = TypeTypeCredentials()
    private init() {}

    func token(for origin: URL) -> String? {
        let query: [String: Any] = [kSecClass as String: kSecClassGenericPassword,
            kSecAttrService as String: "org.typetype.tvOS.auth",
            kSecAttrAccount as String: origin.absoluteString,
            kSecReturnData as String: true, kSecMatchLimit as String: kSecMatchLimitOne]
        var value: CFTypeRef?
        guard SecItemCopyMatching(query as CFDictionary, &value) == errSecSuccess,
              let data = value as? Data else { return nil }
        return String(data: data, encoding: .utf8)
    }

    @discardableResult
    func save(_ token: String, for origin: URL) -> Bool {
        guard !token.isEmpty else { return false }
        let key: [String: Any] = [kSecClass as String: kSecClassGenericPassword,
            kSecAttrService as String: "org.typetype.tvOS.auth",
            kSecAttrAccount as String: origin.absoluteString]
        let updated = SecItemUpdate(key as CFDictionary,
            [kSecValueData as String: Data(token.utf8)] as CFDictionary)
        let result: OSStatus
        if updated == errSecItemNotFound {
            var item = key
            item[kSecValueData as String] = Data(token.utf8)
            item[kSecAttrAccessible as String] = kSecAttrAccessibleAfterFirstUnlockThisDeviceOnly
            result = SecItemAdd(item as CFDictionary, nil)
        } else {
            result = updated
        }
        guard result == errSecSuccess else {
            // Never delete the previously working credential on a write
            // failure (for example after provisioning/keychain changes).
            NSLog("TypeType Keychain auth write failed OSStatus=%d", result)
            return false
        }
        saveDisplayIdentifier(nil, for: origin)
        return true
    }

    /// Optional display-only login identifier for accounts without a public
    /// username. Kept in Keychain alongside credentials, never in UserDefaults.
    func displayIdentifier(for origin: URL) -> String? {
        let query: [String: Any] = [
            kSecClass as String: kSecClassGenericPassword,
            kSecAttrService as String: "org.typetype.tvOS.account-identifier",
            kSecAttrAccount as String: origin.absoluteString,
            kSecReturnData as String: true,
            kSecMatchLimit as String: kSecMatchLimitOne
        ]
        var value: CFTypeRef?
        guard SecItemCopyMatching(query as CFDictionary, &value) == errSecSuccess,
              let data = value as? Data else { return nil }
        return String(data: data, encoding: .utf8)
    }

    func saveDisplayIdentifier(_ identifier: String?, for origin: URL) {
        let key: [String: Any] = [
            kSecClass as String: kSecClassGenericPassword,
            kSecAttrService as String: "org.typetype.tvOS.account-identifier",
            kSecAttrAccount as String: origin.absoluteString
        ]
        guard let identifier, !identifier.isEmpty else {
            SecItemDelete(key as CFDictionary)
            return
        }
        let status = SecItemUpdate(key as CFDictionary,
            [kSecValueData as String: Data(identifier.utf8)] as CFDictionary)
        if status == errSecItemNotFound {
            var item = key
            item[kSecValueData as String] = Data(identifier.utf8)
            item[kSecAttrAccessible as String] = kSecAttrAccessibleAfterFirstUnlockThisDeviceOnly
            let added = SecItemAdd(item as CFDictionary, nil)
            if added != errSecSuccess {
                NSLog("TypeType Keychain label write failed OSStatus=%d", added)
            }
        } else if status != errSecSuccess {
            NSLog("TypeType Keychain label update failed OSStatus=%d", status)
        }
    }

    func clear(for origin: URL) {
        SecItemDelete([kSecClass as String: kSecClassGenericPassword,
            kSecAttrService as String: "org.typetype.tvOS.auth",
            kSecAttrAccount as String: origin.absoluteString] as CFDictionary)
        clearRefreshToken(for: origin)
        saveDisplayIdentifier(nil, for: origin)
    }
}

