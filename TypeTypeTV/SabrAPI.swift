/// Unlike /segments, the server's /prefetch handler rebuilds the window
/// and registers new missing audio/video segment demands. One prefetch only
/// cannot unblock the *next* missing track after a forward seek completes.
enum SabrWindowPrefetchPolicy {
    static let minimumInterval: TimeInterval = 5

    static func shouldRefresh(last: Date?, now: Date,
                              interval: TimeInterval = minimumInterval) -> Bool {
        guard let last else { return true }
        return now.timeIntervalSince(last) >= max(0.05, interval)
    }
}

final class SabrService: @unchecked Sendable {
    private let origin: URL
    private let base: URL
    private let session: URLSession
    private let prefetchInterval: TimeInterval
    private let json = JSONDecoder()
    private let encoder = JSONEncoder()

    init(api: TypeTypeAPI, session injectedSession: URLSession? = nil,
         prefetchInterval: TimeInterval = SabrWindowPrefetchPolicy.minimumInterval) {
        origin = api.origin
        base = api.origin.appendingPathComponent("api", isDirectory: true)
        session = injectedSession ?? TVNetwork.session(for: origin)
        self.prefetchInterval = max(0.05, prefetchInterval)
    }

    func bootstrap(videoURL: String) async throws -> SabrBootstrap {
        try await request("streams/youtube/sabr/bootstrap", query: [URLQueryItem(name: "url", value: videoURL)])
    }

    func guestLogin() async throws {
        struct Guest: Decodable { let token: String }
        let reply: Guest = try await request("auth/guest", method: "POST", body: Data())
        guard !reply.token.isEmpty else {
            throw SabrFailure.invalidResponse("guest token is empty")
        }
        // A device-code account sign-in might complete while this request is
        // in flight. Never overwrite that user's freshly stored credentials.
        guard SabrGuestAuthPolicy.mayStoreGuestToken(
            existingToken: TypeTypeCredentials.shared.token(for: origin)
        ) else { return }
        TypeTypeCredentials.shared.save(reply.token, for: origin)
    }

    func deviceLoginStart() async throws -> DeviceStart {
        do {
            return try await request("auth/device/start", method: "POST",
                                     body: try encoder.encode(DeviceStartRequest(deviceName: "TypeType tvOS")))
        } catch SabrFailure.server(404, _) {
            // Released servers before the device-code API return HTTP 404.
            // Keep other HTTP and transport failures visible as-is.
            throw DeviceLoginError.serverUnsupported
        }
    }

    func deviceLoginPoll(_ code: String) async throws -> DeviceToken {
        let (data, response) = try await read(
            base.appendingPathComponent("auth/device/token"), method: "POST",
            body: try encoder.encode(DeviceTokenRequest(deviceCode: code)),
            allowedStatuses: [200, 400], pathForError: "auth/device/token"
        )
        var reply = try json.decode(DeviceToken.self, from: data)
        if response.statusCode == 200, reply.accessToken?.isEmpty == false {
            reply.refreshToken = TVAuthCookie.token(from: response, for: origin)
        }
        return reply
    }

    func start(videoId: String, selection: SabrSelection, positionMs: Int64 = 0,
               refreshUpstream: Bool = false) async throws -> SabrSessionReply {
        guard videoId.range(of: "^[A-Za-z0-9_-]{11}$", options: .regularExpression) != nil else {
            throw SabrFailure.invalidResponse("videoId")
        }
        // Local TypeType-Server extension. Without the local server patch the
        // optional query parameter is ignored, leaving normal playback intact.
        let query = refreshUpstream
            ? [URLQueryItem(name: "refreshUpstream", value: "true")] : []
        return try await request("sabr/playback/\(videoId)", query: query, method: "POST",
                                 body: try encoder.encode(SabrSessionRequest(selection, positionMs: positionMs)),
                                 allowedStatuses: [200, 202])
    }

    func seek(sessionId: String, selection: SabrSelection, positionMs: Int64) async throws -> SabrSessionReply {
        try await request("sabr/playback/\(sessionId)/seek", method: "POST",
                          body: try encoder.encode(SabrSessionRequest(selection, positionMs: positionMs)),
                          allowedStatuses: [200, 202])
    }

    /// Tell the unmodified TypeType server that the session is no longer used.
    /// Its DELETE endpoint is idempotent and returns HTTP 204.
    func release(sessionId: String) async throws {
        guard !sessionId.isEmpty else { return }
        let _: EmptyReply = try await request("sabr/playback/\(sessionId)",
            method: "DELETE", allowedStatuses: [200, 204], allowEmpty: true)
    }

    func window(sessionId: String, selection: SabrSelection, generation: Int64,
                positionMs: Int64, ranges: [SabrBufferedRange] = [],
                buffer: SabrBufferSettings = SabrBufferSettings(),
                requestedBufferGoalMs: Int? = nil) async throws -> SabrWindow {
        let body = try encoder.encode(SabrWindowRequest(
            selection, generation: generation, positionMs: positionMs,
            ranges: ranges, buffer: buffer,
            requestedBufferGoalMs: requestedBufferGoalMs
        ))
        let path = "sabr/playback/\(sessionId)"
        let _: EmptyReply = try await request(path + "/position", method: "POST", body: body, allowedStatuses: [200, 202, 204], allowEmpty: true)
        var lastPrefetch: Date?
        var prefetchAttempts = 0
        let startedAt = Date()
        let deadline = startedAt.addingTimeInterval(25)
        for _ in 0..<60 {
            try Task.checkCancellation()
            let now = Date()
            if now > deadline {
                throw SabrFailure.invalidResponse("segment window timed out")
            }
            if SabrWindowPrefetchPolicy.shouldRefresh(
                last: lastPrefetch, now: now, interval: prefetchInterval
            ) {
                // Re-register newly blocked tracks after previous demands
                // finish. The server deduplicates identical demands. This is
                // strictly serial and rate-limited: never hammer /prefetch.
                if prefetchAttempts > 0 {
                    NSLog("TypeType SABR WINDOW re-prefetch attempt=%d elapsedMs=%d",
                          prefetchAttempts + 1,
                          Int(now.timeIntervalSince(startedAt) * 1_000))
                }
                lastPrefetch = now
                prefetchAttempts += 1
                let _: EmptyReply = try await request(path + "/prefetch", method: "POST",
                                                       body: body, allowedStatuses: [200, 202, 204], allowEmpty: true)
            }
            let answer: SabrWindow = try await request(path + "/segments", method: "POST",
                                                       body: body, allowedStatuses: [200, 202])
            if answer.ready {
                guard answer.generation == generation,
                      answer.sessionId == nil || answer.sessionId == sessionId,
                      answer.audio != nil else { throw SabrFailure.invalidResponse("window generation/tracks") }
                return answer
            }
            if answer.recoveryAction == "retry_fresh_session" {
                // "Expired" is our client-side name for the server's
                // instruction to create a fresh playback session; it does
                // not prove that the session token itself timed out.
                // Only log known categories, never the raw terminalError.
                NSLog("TypeType SABR SERVER recovery action=%@ state=%@ cause=%@",
                      SabrServerRecoveryDiagnostics.action(answer.recoveryAction),
                      SabrServerRecoveryDiagnostics.state(answer.status),
                      SabrServerRecoveryDiagnostics.category(answer.terminalError))
                throw SabrFailure.expired
            }
            if let terminal = answer.terminalError {
                NSLog("TypeType SABR SERVER terminal state=%@ cause=%@",
                      SabrServerRecoveryDiagnostics.state(answer.status),
                      SabrServerRecoveryDiagnostics.category(terminal))
                throw SabrFailure.invalidResponse(terminal)
            }
            try await Task.sleep(nanoseconds: UInt64(min(2000, max(150, answer.retryAfterMs ?? 300))) * 1_000_000)
        }
        throw SabrFailure.invalidResponse("segment window timed out")
    }

    /// A /segments window may already be ready while one of its listed
    /// progressive MP4 fragments still returns HTTP 202. Re-register the
    /// missing track demands during a long fragment download, without
    /// changing playback position or creating a new session. The caller
    /// schedules this sparingly and cancels it when all media is cached.
    func refreshMediaPrefetch(sessionId: String, selection: SabrSelection,
                              generation: Int64, positionMs: Int64,
                              buffer: SabrBufferSettings,
                              requestedBufferGoalMs: Int) async throws {
        let body = try encoder.encode(SabrWindowRequest(
            selection, generation: generation, positionMs: positionMs,
            ranges: SabrSequentialWindowPolicy.advertisedRanges,
            buffer: buffer, requestedBufferGoalMs: requestedBufferGoalMs
        ))
        let _: EmptyReply = try await request(
            "sabr/playback/\(sessionId)/prefetch", method: "POST",
            body: body, allowedStatuses: [200, 202, 204], allowEmpty: true
        )
    }

    func fragmentData(_ reference: String, sessionId: String, itag: Int, generation: Int64) async throws -> Data {
        guard let address = URL(string: reference, relativeTo: base)?.absoluteURL,
              address.scheme == origin.scheme, address.host == origin.host, address.port == origin.port,
              address.path.hasPrefix(
                (base.path.hasSuffix("/") ? base.path : base.path + "/") +
                "sabr/playback/\(sessionId)/\(itag)/"
              ),
              URLComponents(url: address, resolvingAgainstBaseURL: false)?
                .queryItems?.first(where: { $0.name == "generation" })?.value == String(generation)
        else { throw SabrFailure.invalidResponse("media URL is outside TypeType session") }
        return try await read(address, method: "GET", body: nil,
                              allowedStatuses: [200], pathForError: "segment").data
    }

    private func request<T: Decodable>(_ path: String, query: [URLQueryItem] = [], method: String = "GET",
        body: Data? = nil, allowedStatuses: Set<Int> = [200], allowEmpty: Bool = false) async throws -> T {
        var components = URLComponents(url: base.appendingPathComponent(path), resolvingAgainstBaseURL: false)
        components?.queryItems = query.isEmpty ? nil : query
        guard let address = components?.url else { throw SabrFailure.invalidResponse("URL") }
        let data = try await read(address, method: method, body: body,
                                  allowedStatuses: allowedStatuses, pathForError: path).data
        if allowEmpty, let empty = EmptyReply() as? T { return empty }
        return try json.decode(T.self, from: data)
    }

    private func read(_ address: URL, method: String, body: Data?, allowedStatuses: Set<Int>,
                      pathForError: String) async throws -> (data: Data, response: HTTPURLResponse) {
        var req = URLRequest(url: address)
        req.httpMethod = method
        if method == "POST" {
            req.httpBody = body ?? Data("{}".utf8)
            req.setValue("application/json", forHTTPHeaderField: "Content-Type")
        }
        req.setValue(pathForError == "segment" ? "*/*" : "application/json", forHTTPHeaderField: "Accept")
        req.setValue("TypeTypeTV-tvOS/0.1", forHTTPHeaderField: "User-Agent")
        if let token = TypeTypeCredentials.shared.token(for: origin) {
            req.setValue("Bearer \(token)", forHTTPHeaderField: "Authorization")
        }
        // TypeType's segment endpoint uses HTTP 202 for a valid but not-yet
        // downloaded segment. Retrying is part of the API contract; never
        // pass the JSON 202 response body to the MP4 demuxer.
        let isMediaSegment = pathForError == "segment"
        let mediaStarted = Date()
        let mediaDeadline = mediaStarted.addingTimeInterval(25)
        // The URL contains a private playback session token. Extract only
        // numeric itag/sequence diagnostics, never log the URL or token.
        let segmentItag = isMediaSegment
            ? Int(address.pathComponents.dropLast(2).last ?? "") ?? -1 : -1
        let segmentSequence = isMediaSegment
            ? Int(address.lastPathComponent) ?? -1 : -1
        var segmentPolls = 0
        var didRefreshAuth = false
        while true {
            try Task.checkCancellation()
            let (data, response) = try await session.data(for: req)
            guard let http = response as? HTTPURLResponse else {
                throw SabrFailure.invalidResponse("HTTP response")
            }
            if http.statusCode == 401, !didRefreshAuth,
               let header = req.value(forHTTPHeaderField: "Authorization"),
               header.hasPrefix("Bearer ") {
                didRefreshAuth = true
                let stale = String(header.dropFirst("Bearer ".count))
                if let renewed = try? await TVAuthRefreshCoordinator.shared.refresh(
                    origin: origin, session: session, failedAccessToken: stale
                ), renewed != stale {
                    req.setValue("Bearer \(renewed)", forHTTPHeaderField: "Authorization")
                    continue
                }
            }
            if isMediaSegment && http.statusCode == 202 {
                segmentPolls += 1
                let preparing = try? JSONDecoder().decode(SabrSegmentPreparing.self, from: data)
                let fromHeader = SabrRetryAfter.seconds(http.value(forHTTPHeaderField: "Retry-After"))
                    .map { $0 * 1000 }
                let delay = min(2_000, max(150, preparing?.retryAfterMs ?? fromHeader ?? 300))
                let elapsedMs = Int(Date().timeIntervalSince(mediaStarted) * 1_000)
                // One initial diagnostic, then periodic updates, then a
                // definitive timeout. This distinguishes a slow network
                // from the server never making a particular media seq ready.
                if segmentPolls == 1 || segmentPolls.isMultiple(of: 10) {
                    NSLog("TypeType SABR SEGMENT pending itag=%d seq=%d polls=%d elapsedMs=%d retryMs=%d status=%@",
                          segmentItag, segmentSequence, segmentPolls, elapsedMs,
                          delay, String((preparing?.status ?? "unknown").prefix(32)))
                }
                guard segmentPolls < 60 && Date() < mediaDeadline else {
                    NSLog("TypeType SABR SEGMENT timeout itag=%d seq=%d polls=%d elapsedMs=%d status=%@",
                          segmentItag, segmentSequence, segmentPolls, elapsedMs,
                          String((preparing?.status ?? "unknown").prefix(32)))
                    throw SabrFailure.stalled("SABR segment still preparing after retries")
                }
                try await Task.sleep(nanoseconds: UInt64(delay) * 1_000_000)
                continue
            }
            guard allowedStatuses.contains(http.statusCode) else {
            if [404, 410, 422].contains(http.statusCode),
               let issue = try? JSONDecoder().decode(TVStreamProblem.self, from: data),
               issue.isPermanentlyUnavailable {
                throw SabrFailure.unavailable
            }
            if [429, 503, 504].contains(http.statusCode),
               let wait = SabrRetryAfter.seconds(
                   http.value(forHTTPHeaderField: "Retry-After")
               ) {
                throw SabrFailure.throttled(http.statusCode, pathForError, wait)
            }
            throw SabrFailure.server(http.statusCode, pathForError)
            }
            return (data, http)
        }
    }
}

private struct SabrSegmentPreparing: Decodable {
    let retryAfterMs: Int?
    let status: String?
}

struct TVStreamProblem: Decodable {
    let error: String
    let code: String

    var isPermanentlyUnavailable: Bool {
        ["no_playable_streams", "sabr_content_unavailable",
         "content_unavailable", "video_unavailable"].contains(code)
    }
}

