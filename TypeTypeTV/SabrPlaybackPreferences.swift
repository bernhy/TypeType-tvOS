import Foundation

/// TypeType account preferences affect the initial stream choice. Device
/// limits and explicit in-player choices always take priority.
enum SabrPlaybackPreferences {
    static func defaultHeight(_ server: String?, deviceMax: Int) -> Int {
        let raw = (server ?? "").lowercased()
            .trimmingCharacters(in: .whitespacesAndNewlines)
        let height: Int?
        if raw == "4k" || raw == "uhd" {
            height = 2160
        } else if raw.hasSuffix("p") {
            height = Int(raw.dropLast())
        } else {
            height = nil
        }
        return min(deviceMax, height ?? deviceMax)
    }

    static func preferredVideo(_ candidates: [SabrSelection],
                               defaultQuality: String?,
                               deviceMax: Int) -> SabrSelection? {
        let cap = defaultHeight(defaultQuality, deviceMax: deviceMax)
        return candidates.first { ($0.video.height ?? 0) <= cap }
            ?? candidates.first
    }

    static func preferredAudio(
        _ tracks: [SabrBootstrap.Audio],
        language: String?, preferOriginal: Bool
    ) -> SabrBootstrap.Audio? {
        if preferOriginal {
            return tracks.first { $0.isOriginal == true } ?? tracks.first
        }
        if let language, !language.isEmpty {
            let code = language.lowercased().split(separator: "-").first.map(String.init) ?? ""
            if let found = tracks.first(where: {
                ($0.audioLocale ?? "").lowercased().hasPrefix(code)
            }) { return found }
        }
        return tracks.first
    }

    static func preferredSubtitle(
        _ tracks: [SabrBootstrap.Subtitle], language: String
    ) -> SabrBootstrap.Subtitle? {
        let code = language.lowercased().split(separator: "-").first.map(String.init) ?? ""
        return tracks.sorted {
            ($0.isAutoGenerated ?? false) == false &&
            ($1.isAutoGenerated ?? false) == true
        }.first {
            ($0.languageTag ?? "").lowercased().hasPrefix(code)
        }
    }
}
