import Foundation

/// TypeType account preferences affect the initial stream choice. Device
/// limits and explicit in-player choices always take priority.
enum SabrPlaybackPreferences {
    static func defaultHeight(_ server: String?, deviceMax: Int) -> Int {
        let raw = (server ?? "").lowercased()
            .trimmingCharacters(in: .whitespacesAndNewlines)
        let height: Int?
        if raw == "4k" || raw == "uhd" {
            height = 2160
        } else if raw.hasSuffix("p") {
            height = Int(raw.dropLast())
        } else {
            height = nil
        }
        return min(deviceMax, height ?? deviceMax)
    }

    /// The automatic quality choice must prefer a real VideoToolbox
    /// hardware decoder before considering an optional software codec.
    /// Explicit manual itags are handled by the player and take precedence.
    ///
    /// Keep the user's requested height cap first, then choose hardware
    /// support within that cap; only if no suitable hardware stream exists
    /// may software decoding be used when it has been explicitly enabled.
    static func orderedAutomaticVideos(
        _ candidates: [SabrSelection],
        defaultQuality: String?,
        deviceMax: Int,
        hardwareSupported: (String) -> Bool = { HardwareCodec.supported($0) }
    ) -> [SabrSelection] {
        let cap = defaultHeight(defaultQuality, deviceMax: deviceMax)
        let within = candidates.filter { ($0.video.height ?? 0) <= cap }
        let above = candidates.filter { ($0.video.height ?? 0) > cap }
        func preferredHardwareFirst(_ entries: [SabrSelection]) -> [SabrSelection] {
            let hardware = entries.filter { hardwareSupported($0.video.codec) }
            let software = entries.filter { !hardwareSupported($0.video.codec) }
            return hardware + software
        }
        return preferredHardwareFirst(within) + preferredHardwareFirst(above)
    }

    /// A manually requested resolution should not silently fall straight
    /// back to a lower-resolution automatic choice when a different codec
    /// at the same height is still available for a real decoder attempt.
    /// Preserve the exact requested itag first and use the normal automatic
    /// order only after same-height alternatives have been tried.
    static func orderedForManualVideo(
        _ requested: SabrSelection,
        automaticOrder: [SabrSelection]
    ) -> [SabrSelection] {
        let alternatives = automaticOrder.filter {
            $0.video.itag != requested.video.itag &&
                $0.video.height == requested.video.height
        }
        // Never raise the resolution above what the user selected.
        // Decrease one resolution tier at a time and exhaust that tier's
        // alternative codecs before moving to the next lower tier.
        let lower = automaticOrder.enumerated()
            .filter {
                $0.element.video.itag != requested.video.itag &&
                    ($0.element.video.height ?? 0) < (requested.video.height ?? 0)
            }
            .sorted { left, right in
                let lh = left.element.video.height ?? 0
                let rh = right.element.video.height ?? 0
                return lh == rh ? left.offset < right.offset : lh > rh
            }
            .map(\.element)
        return [requested] + alternatives + lower
    }

    static func preferredVideo(_ candidates: [SabrSelection],
                               defaultQuality: String?,
                               deviceMax: Int) -> SabrSelection? {
        orderedAutomaticVideos(candidates, defaultQuality: defaultQuality,
                               deviceMax: deviceMax).first
    }

    static func preferredAudio(
        _ tracks: [SabrBootstrap.Audio],
        language: String?, preferOriginal: Bool
    ) -> SabrBootstrap.Audio? {
        if preferOriginal {
            return tracks.first { $0.isOriginal == true } ?? tracks.first
        }
        if let language, !language.isEmpty {
            let code = language.lowercased().split(separator: "-").first.map(String.init) ?? ""
            if let found = tracks.first(where: {
                ($0.audioLocale ?? "").lowercased().hasPrefix(code)
            }) { return found }
        }
        return tracks.first
    }

    static func preferredSubtitle(
        _ tracks: [SabrBootstrap.Subtitle], language: String
    ) -> SabrBootstrap.Subtitle? {
        let code = language.lowercased().split(separator: "-").first.map(String.init) ?? ""
        return tracks.sorted {
            ($0.isAutoGenerated ?? false) == false &&
            ($1.isAutoGenerated ?? false) == true
        }.first {
            ($0.languageTag ?? "").lowercased().hasPrefix(code)
        }
    }
}
